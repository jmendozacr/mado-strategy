"""Extracts EventRecords from the causal-lookahead-audit's corrected D3/C2 ledger.

Source (read-only input; this module must never write into audit/):
    audit/2026-11-17-causal-lookahead-audit/trades_d3_c2_2015plus_run2.csv

Why this source and not audit/2026-11-17-eurusd-usdcad-audusd/trades.csv --
see docs/02-source-inventory.md for the full reasoning. In short: this ledger
was produced by the audit's own corrected pipeline (causal_intrabar.py's
first_fillable_index logic, the key-level cross-grid timestamp bridge, and the
bar open/close availability fix documented in design-c1-c2.md). A repo-wide
grep for those same fix markers inside detector/ returns zero hits, so those
causal-correctness fixes were never merged into detector/backtest/simulate.py
or detector/entries/model1.py -- the other ledger was generated by calling
that unmodified production code, so it likely still carries the premature-
fill bug this very audit found. Do not substitute it here without re-running
that grep check and updating the source inventory doc.

This extractor only has to be correct for the columns this specific CSV
actually has. If the source is swapped for a sibling arm file (trades_c1.csv,
trades_c2.csv, ...) with a different column set, this module's assumptions
must be re-verified, not silently reused.
"""
from __future__ import annotations

import csv
from datetime import datetime
from pathlib import Path

from schema.events import (
    EventRecord,
    ExitReasonBasis,
    FeaturesAtStop,
    FeaturesPreEntry,
    Identification,
    Outcome,
    OriginalOperation,
)

SOURCE_RELATIVE_PATH = "audit/2026-11-17-causal-lookahead-audit/trades_d3_c2_2015plus_run2.csv"
SOURCE_VERSION = "d3_c2_2015plus_run2"

REQUIRED_COLUMNS = (
    "pair", "arm", "stable_id", "model", "direction",
    "feeder_ref_available_ts", "activation_instant_ts", "model1_available_ts",
    "order_placed_ts", "entry_timestamp_broker", "entry_price", "stop_loss",
    "take_profit", "partial_exit_index", "exit_timestamp_broker", "exit_price",
    "outcome", "r_multiple", "ambiguous_bar", "gap_filled",
)


def _parse_ts(value: str) -> datetime | None:
    if not value:
        return None
    return datetime.fromisoformat(value)


def _parse_bool(value: str) -> bool:
    return value == "True"


def _parse_float(value: str) -> float | None:
    # Empty for "open" (right-censored, still-open) trades: exit_price and
    # r_multiple are not yet knowable, not zero -- keep them None, never 0.0.
    if value == "":
        return None
    return float(value)


def _exit_reason(outcome: Outcome) -> tuple[str | None, ExitReasonBasis]:
    # The source ledger has no `exit_reason` column. detector's own
    # backtest.Trade dataclass models only stop_loss/take_profit exits (no
    # time-based exit exists in this engine), so we infer exit_reason from
    # `outcome` under that documented assumption. This is INFERRED, never
    # observed -- `exit_reason_basis` on every record says so explicitly.
    # outcome == "open" means the trade was still running when the source
    # data ended (right-censored) -- there is no exit yet, by construction.
    if outcome is Outcome.LOSS:
        return "stop_loss", ExitReasonBasis.INFERRED_BINARY
    if outcome is Outcome.WIN:
        return "take_profit", ExitReasonBasis.INFERRED_BINARY
    return None, ExitReasonBasis.UNKNOWN


def extract(repo_root: Path) -> list[EventRecord]:
    source_path = repo_root / SOURCE_RELATIVE_PATH
    if not source_path.exists():
        raise FileNotFoundError(
            f"expected read-only source at {source_path} -- do not substitute "
            "another ledger without updating docs/02-source-inventory.md"
        )

    records: list[EventRecord] = []
    with source_path.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        missing = [c for c in REQUIRED_COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(
                f"{source_path} is missing expected column(s): {missing} -- "
                "the source ledger's schema changed; update this extractor "
                "deliberately, do not patch around it silently"
            )

        for row in reader:
            outcome = Outcome(row["outcome"])
            exit_reason, exit_reason_basis = _exit_reason(outcome)
            entry_price = float(row["entry_price"])
            stop_loss = float(row["stop_loss"])
            take_profit = float(row["take_profit"])
            activation_ts = _parse_ts(row["activation_instant_ts"])
            order_placed_ts = _parse_ts(row["order_placed_ts"])
            entry_ts = _parse_ts(row["entry_timestamp_broker"])
            exit_ts = _parse_ts(row["exit_timestamp_broker"])

            identification = Identification(
                event_id=row["stable_id"],
                source_path=SOURCE_RELATIVE_PATH,
                source_version=SOURCE_VERSION,
                instrument=row["pair"],
                session_label=row["model"],
                config_id=row["arm"],
                original_direction=row["direction"],
            )
            operation = OriginalOperation(
                entry_price=entry_price,
                stop_loss=stop_loss,
                take_profit=take_profit,
                risk_price=abs(entry_price - stop_loss),
                activation_ts=activation_ts,
                order_placed_ts=order_placed_ts,
                entry_ts=entry_ts,
                exit_ts=exit_ts,
                exit_price=_parse_float(row["exit_price"]),
                outcome=outcome,
                r_multiple=_parse_float(row["r_multiple"]),
                exit_reason=exit_reason,
                exit_reason_basis=exit_reason_basis,
                ambiguous_bar=_parse_bool(row["ambiguous_bar"]),
                gap_filled=_parse_bool(row["gap_filled"]),
                has_partial_exit=bool(row.get("partial_exit_index")),
            )
            time_from_activation_to_order_s = (
                (order_placed_ts - activation_ts).total_seconds()
                if activation_ts and order_placed_ts
                else None
            )
            planned_rr = (
                abs(take_profit - entry_price) / abs(entry_price - stop_loss)
                if entry_price != stop_loss
                else None
            )
            features_pre_entry = FeaturesPreEntry(
                feeder_ref_available_ts=_parse_ts(row["feeder_ref_available_ts"]),
                activation_instant_ts=activation_ts,
                model1_available_ts=_parse_ts(row["model1_available_ts"]),
                order_placed_ts=order_placed_ts,
                time_from_activation_to_order_s=time_from_activation_to_order_s,
                planned_risk_price=abs(entry_price - stop_loss),
                planned_reward_price=abs(take_profit - entry_price),
                planned_rr=planned_rr,
            )
            speed_to_stop_s = (
                (exit_ts - entry_ts).total_seconds() if entry_ts and exit_ts else None
            )
            features_at_stop = FeaturesAtStop(
                exit_ts=exit_ts,
                exit_price=operation.exit_price,
                outcome=outcome,
                r_multiple=operation.r_multiple,
                speed_to_stop_s=speed_to_stop_s,
                ambiguous_bar=operation.ambiguous_bar,
                gap_filled=operation.gap_filled,
            )
            records.append(
                EventRecord(
                    identification=identification,
                    operation=operation,
                    features_pre_entry=features_pre_entry,
                    features_at_stop=features_at_stop,
                    post_stop_outcomes=[],
                )
            )
    return records
